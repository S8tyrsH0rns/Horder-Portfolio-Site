	<h2>/ The Idea</h2>
	<p>This project happened a few years ago, so this post will be more of a retrospective. With plenty of decisions I made at the time which I would approach differently now. Though sometimes I feel like looking back can show you how your skills have developed over time.</p>
	<p>The coursework briefing was to create a promotional piece of software using either AR or VR technology. Most of the other students went with AR but as a gamer who had recently gotten an Oculus Rift S I was adamant that I wanted to make a VR product. I decided I wanted to create a tour of the whole school, including videos for key departments. As the school computers couldn't run Unreal Engine (my engine of choice) I realised that a majority of development would have to be done at home.</p>
	
	<h2>/ Creating the Tour</h2>
	<p>As I couldn't create a program in class I focused my time creating the 3D models for the school. Using Blender I made assets using simple cubes to create a boxy replica of individual classrooms. I spent a lot of time trying to match scale and form as closely to the real rooms as possible. Being unfamiliar with 3D Modelling at the time I struggled to properly texture the models, often using flat colours to reduce time spent per classroom. I also created a simplified miniature version of the school, colour coding each building to differentiate between blocks.</p>
	<p>During asset creation I began working on development simultaneously at home. I made the program using Unreal Engine, learning basic C++ to create player controls and making use of terrain tools and the media player element in the scene editor to add informational videos on each department created.</p>
	
	<h2>/ Challenges and Problem Solving</h2>
	<p>Taking on the task of creating a whole-school tour, including hand modelling the school to accurate measurements quickly showed itself to be a much bigger task than anticipated. This was my first real experience of scope creep, being overly enthusiastic meant that I had to quickly scale back my plans. I ended up focusing on 3 main departments: Maths, English, and IT. To make up for the fewer classrooms, I made informational videos featuring each departments head of subject.</p>
	
	<h2>/ Looking Back</h2>
	<p>Looking back it makes me happy to know I can spot errors I made then almost on instinct and even though it wasn't a perfect product I am still incredibly proud of myself for finishing it. I remember playing the tour over and over just to enjoy something I made.</p>
	<p>Receiving an award for best in class cemented my decision to go on to study Computer Science at University. I often experience imposter syndrome as a University Student, comparing myself to my peers and feeling inadequate or behind. Recently, though I've been trying to focus less on comparison and simply enjoy the subject. It's brought me so much more love and curiosity for Computer Science and a fascination with all the new topics I've been exploring.</p>
